#!/usr/bin/env python3
"""Convert a binary file into a deterministic C header.

The output is deliberately simple so it can be included by freestanding kernel
code without libc or generated build-system dependencies.
"""

from __future__ import annotations

import argparse
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("symbol")
    args = parser.parse_args()

    data = args.input.read_bytes()
    args.output.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "/* Generated by tools/build/embed-binary.py. Do not edit. */",
        "#pragma once",
        "",
        f"static const unsigned char {args.symbol}[] __attribute__((aligned(16))) = {{",
    ]

    for offset in range(0, len(data), 12):
        chunk = data[offset : offset + 12]
        encoded = ", ".join(f"0x{byte:02x}" for byte in chunk)
        lines.append(f"    {encoded},")

    lines.extend(
        [
            "};",
            f"static const unsigned long {args.symbol}_len = {len(data)}UL;",
            "",
        ]
    )
    args.output.write_text("\n".join(lines), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
